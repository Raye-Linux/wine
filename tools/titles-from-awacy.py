"""Turns the community anti-cheat list into a Raye titles overlay.

    tools/titles-from-awacy.py games.json > release/windows/titles/00-upstream.titles

The 00- in the name is not decoration: titles files are read in name
order and the last answer wins, so this generated list sits BELOW
50-raye.titles and can never bury a verdict somebody measured.

games.json comes from the Are We Anti-Cheat Yet? project
(github.com/AreWeAntiCheatYet/AreWeAntiCheatYet). It is the only list
anyone keeps of which publishers have turned their anti-cheat's Linux
module on, and it cites a source per title. Download it, pass the path,
and record the commit it came from with --commit so the file says where
its facts are from and how old they are.

What this does NOT do, on purpose:

- it never writes state = works. That column is Raye's own verdict and
  needs a machine and a date; a community list cannot supply either.
  Every title here comes out `untested` unless its anti-cheat is one
  that cannot work outside Windows at all, which is `blocked`.
- it keeps only the titles where the list has a definite answer about
  the publisher (Supported or Denied). "Running" means the community got
  it going without the publisher doing anything, and "Broken" means
  nobody did: neither is a fact about a publisher, and shipping them as
  one would put a guess in front of a user.
"""
import argparse
import json
import sys

# Anti-cheats that cannot run outside Windows by their own design: a
# kernel driver, or a tamper guard whose publisher withdrew this system.
# For these, "blocked" is a fact about the software, not a test result.
BY_DESIGN = {"vanguard": "a Windows kernel driver",
             "hyperion": "a tamper guard its publisher withdrew here"}


def slug(name):
    out = []
    for ch in name.lower():
        out.append(ch if ch.isalnum() else "-")
    s = "".join(out)
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-")


def one_line(text):
    return " ".join(str(text).split())


def entries(games):
    seen = {}
    for g in games:
        status = g.get("status")
        if status not in ("Supported", "Denied"):
            continue
        acs = [one_line(a) for a in (g.get("anticheats") or [])]
        key = slug(g.get("name") or "")
        if not key or key in seen:
            continue
        design = [BY_DESIGN[a.lower()] for a in acs if a.lower() in BY_DESIGN]
        if status == "Denied":
            upstream, state = "refused", "blocked"
            if design:
                why_en = "Refused here: its anti-cheat is %s." % design[0]
                why_fr = "Refusé ici : son anti-triche est %s." % (
                    "un pilote noyau Windows" if "kernel" in design[0]
                    else "une protection que son éditeur a retirée ici")
            else:
                why_en = "Its publisher has not turned on the Linux side of its anti-cheat."
                why_fr = "Son éditeur n'a pas activé la partie Linux de son anti-triche."
        else:
            upstream, state = "runtime-enabled", "untested"
            why_en = "Its publisher turned the Linux side of its anti-cheat on; not yet played here."
            why_fr = "Son éditeur a activé la partie Linux de son anti-triche ; pas encore essayé ici."
        seen[key] = dict(name=one_line(g["name"]), state=state, upstream=upstream,
                         anticheat=", ".join(slug(a) for a in acs) or "none",
                         why_en=why_en, why_fr=why_fr)
    return seen


def render(seen, commit, when):
    out = ["# Generated by tools/titles-from-awacy.py -- do not edit by hand.",
           "#",
           "# Every line below is the PUBLISHER's half of the bargain, not ours:",
           "# `upstream` says what the publisher did, `state` stays `untested`",
           "# until somebody plays the title on a real Raye machine and writes",
           "# the machine and the date in 50-raye.titles. A title named here and",
           "# in 50-raye.titles takes the 50- answer: files are read in name",
           "# order and the last one that names a title wins, so this file is",
           "# the lowest answer there is and a verified one always beats it.",
           "#",
           "# And `runtime-enabled` is not `playable here`: this layer ships no",
           "# anti-cheat runtime at all (third-party/sources.txt), so even a",
           "# publisher that did its half leaves these untested. See",
           "# release/windows/README.md.",
           "#",
           "# source: AreWeAntiCheatYet/AreWeAntiCheatYet games.json",
           "#   commit %s" % (commit or "UNRECORDED -- pass --commit"),
           "#   read   %s" % (when or "UNRECORDED -- pass --date"),
           "#   %d titles where that list has a definite answer about the publisher" % len(seen),
           ""]
    for key in sorted(seen):
        e = seen[key]
        out.append("[%s]" % key)
        for field in ("name", "state", "upstream", "anticheat", "why_en", "why_fr"):
            out.append("%-9s = %s" % (field, e[field]))
        out.append("source    = areweanticheatyet.com games.json @ %s: %s"
                   % (commit or "unrecorded",
                      "Denied" if e["state"] == "blocked" else "Supported"))
        out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("games", help="games.json, already downloaded")
    ap.add_argument("--commit", default="", help="the commit it came from")
    ap.add_argument("--date", default="", help="when it was read, YYYY-MM-DD")
    a = ap.parse_args(argv)
    with open(a.games, encoding="utf-8") as f:
        games = json.load(f)
    if not isinstance(games, list):
        print("titles-from-awacy: games.json is not a list of titles", file=sys.stderr)
        return 1
    sys.stdout.write(render(entries(games), a.commit, a.date))
    return 0


if __name__ == "__main__":
    sys.exit(main())
